param(
    [Parameter(Mandatory)][string]$ProjectFile,
    [Parameter(Mandatory)][string]$OutputFile,
    [string]$Namespace='MyTS3Mod'
)
$ErrorActionPreference='Stop'
$meta=Get-Content -LiteralPath $ProjectFile -Raw -Encoding UTF8|ConvertFrom-Json
if($meta.Id -notmatch '^[a-z0-9]+(?:[.-][a-z0-9]+)+$' -or $meta.Id.Length -gt 100){throw 'Choose a valid, unique mod ID.'}
$parsedVersion=$null
if($meta.Version -isnot [string] -or ![Version]::TryParse($meta.Version,[ref]$parsedVersion)){throw 'Invalid mod version.'}
if($meta.Name -isnot [string] -or $meta.Description -isnot [string] -or [string]::IsNullOrWhiteSpace($meta.Name) -or [string]::IsNullOrWhiteSpace($meta.Description)){throw 'Name and Description are required.'}
if($Namespace -notmatch '^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$'){throw 'Use a valid C# root namespace.'}
$framework=@($meta.Dependencies|Where-Object Id -eq 'nl.ts3modding.loader')
if($framework.Count -ne 1 -or [Version]$framework[0].MinimumVersion -lt [Version]'0.8.19'){throw 'Declare one framework dependency with MinimumVersion 0.8.19 or newer.'}
function Literal([string]$value){return ConvertTo-Json -InputObject $value -Compress}
function HelpArray($items){
    $items=@($items|Where-Object {$null -ne $_})
    if($items.Count -gt 64){throw 'At most 64 help entries are allowed per category.'}
    $expressions=@(foreach($item in $items){
        if([string]::IsNullOrWhiteSpace($item.Syntax) -or $item.Syntax.Length -gt 512 -or ([string]$item.Description).Length -gt 2048){throw 'Invalid help entry: Syntax is required (max 512); Description max 2048 characters.'}
        'new ModHelpItem('+(Literal $item.Syntax)+', '+(Literal ([string]$item.Description))+')'
    })
    return 'new ModHelpItem[] { '+($expressions -join ', ')+' }'
}
if($meta.Description.Length -gt 4096){throw 'Description exceeds the help API limit of 4096 characters.'}
$total=$meta.Description.Length
foreach($entry in @($meta.Keybinds)+@($meta.Commands)){if($null -ne $entry){$total+=([string]$entry.Syntax).Length+([string]$entry.Description).Length}}
if($total -gt 32768){throw 'Combined help text exceeds 32768 characters.'}
$source=@"
// Generated from mod-project.json. Do not edit this file.
using TS3Modding.API;
namespace $Namespace
{
    internal static class ModIdentity
    {
        internal const string Id = $(Literal $meta.Id);
        internal const string Name = $(Literal $meta.Name);
        internal const string Version = $(Literal $meta.Version);
        internal const string Description = $(Literal $meta.Description);
        internal const string FrameworkMinimumVersion = $(Literal $framework[0].MinimumVersion);
        internal static ModHelpPage CreateHelp() => new ModHelpPage(Id, Version, Description,
            keybinds: $(HelpArray $meta.Keybinds), commands: $(HelpArray $meta.Commands));
    }
}
"@
$path=[IO.Path]::GetFullPath($OutputFile)
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($path))|Out-Null
[IO.File]::WriteAllText($path,$source,[Text.UTF8Encoding]::new($false))
